import { normalizeText } from 'util/i18n/renderedTranslations';

const MAX_TEXT_LENGTH = 2000;
const MAX_DOM_PATH_DEPTH = 6;

const closestElement = (target: EventTarget | null): HTMLElement | null => {
  if (target instanceof HTMLElement) {
    return target;
  }

  if (target instanceof Node) {
    return target.parentElement;
  }

  return null;
};

/**
 * Text the user selected, otherwise the text of the clicked element. Elements without text, like icon buttons,
 * fall back to their title or aria label.
 */
export const textOfTarget = (target: EventTarget | null): string => {
  const selection = window.getSelection?.()?.toString();

  if (selection && normalizeText(selection)) {
    return normalizeText(selection).slice(0, MAX_TEXT_LENGTH);
  }

  const element = closestElement(target);

  if (!element) {
    return '';
  }

  const text =
    element.innerText ||
    element.textContent ||
    element.getAttribute('title') ||
    element.getAttribute('aria-label') ||
    element.closest('[title]')?.getAttribute('title') ||
    '';

  return normalizeText(text).slice(0, MAX_TEXT_LENGTH);
};

const describeElement = (element: Element) => {
  const testId = element.getAttribute('data-testid');

  if (element.id) {
    return `${element.tagName.toLowerCase()}#${element.id}`;
  }

  return testId ? `${element.tagName.toLowerCase()}[data-testid="${testId}"]` : element.tagName.toLowerCase();
};

/**
 * Short description of where the element is, e.g. `nav > ul > li > a[data-testid="x"]`, to help finding texts without key.
 * Class names are left out, because the ones generated by styled-components change with every build.
 */
export const domPathOfTarget = (target: EventTarget | null): string => {
  const parts: Array<string> = [];
  let element: Element | null = closestElement(target);

  while (element && element !== document.body && parts.length < MAX_DOM_PATH_DEPTH) {
    parts.unshift(describeElement(element));

    if (element.id) {
      break;
    }

    element = element.parentElement;
  }

  return parts.join(' > ');
};

/** Form fields keep the browser's context menu, so copying and pasting still works there. */
export const isEditableTarget = (target: EventTarget | null) => {
  const element = closestElement(target);

  return !!element?.closest('input, textarea, select, [contenteditable="true"], .ace_editor, .cm-editor');
};
