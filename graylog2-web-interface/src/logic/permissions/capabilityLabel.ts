import i18n from 'i18n';

/** Translated name of a capability, which the server sends as English title (Viewer, Manager, Owner). */
const capabilityLabel = (title: string): string =>
  i18n.t(`permissions.capabilities.${String(title).toLowerCase()}`, { ns: 'users', defaultValue: title });

export default capabilityLabel;
